#!/usr/bin/env python3
"""
Bake Sam's "Death Touch" art into the necrotic death overlay (deathTouch) for the painted map.

    python scripts/vfx/bake_death_touch.py <Death-Touch-Source-Sheet.png> [--preview out.png]

Sam supplied the pack on 2026-10-25: "This is the effect to superimpose on creatures/characters that succumb to
a necrotic spell ... superimposed on their pixel art and they become a clump of bones if they are a NPC or
opponent." The source is not committed (2.3 MB raster): a 1254x1254, 4x4 atlas, ~313 px per cell, opaque on
black, generated by an image model.

WHAT THE SOURCE IS. Not a pure effect: every cell has a photoreal ARMORED REVENANT baked in (the pack's README:
"Green-black blaze wraps an armored target"). Drawn as-is over a pixel sprite it would put a second, different
body on top of the creature. So only the LIGHT is kept -- the green-yellow blaze, the spectral ribs and skull it
lights up, and the ash -- and the dark armour, cloth and black are keyed out. The creature's own sprite is the
body; the overlay is what is happening to it.

KEY. Chroma + brightness, not the luminance key: the armour has bright grey-brown speculars that a luminance
key would keep. Glow pixels are green-yellow (G high, B low, G >= R); armour is near-neutral (R ~ G ~ B).
   green = G - max(B, 0.55 * R) ; alpha = smoothstep over green and over G
Colour is un-premultiplied off black so it composites like the art did.

PIXEL LOOK. The map's figures are pixel art (the HD-2D ruling, 2026-09-24), so the light is cut down to a
CELL x CELL grid with box filtering and quantised to a small green ramp, like the other px* sheets. The page
draws with smoothing off, so it stays crisp at any size.

FRAMES. 16 in the source: 1 ignites, 5-10 the blaze peaks and the ribs flare, 11-14 it sheds as ash, 15-16 cool
back toward 1 (it was built to loop). The death plays them once, in order; the page swaps the body for the bones
at SWAP (written to the manifest) so the ash falls on the bones.

VERIFY NUMERICALLY: prints alpha coverage per frame (rises to the peak then falls) and corner alpha (0).
"""
import json, os, sys
import numpy as np
from PIL import Image

KEY, CELL, N, FPS, SWAP = "deathTouch", 112, 16, 9, 9
RAMP = [(28, 52, 10), (54, 96, 16), (92, 150, 24), (140, 200, 36), (190, 236, 70), (226, 252, 140), (248, 255, 210)]
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, "public", "vfx")


def smooth(x, a, b):
    t = np.clip((x - a) / (b - a), 0, 1)
    return t * t * (3 - 2 * t)


def cells(src):
    im = np.asarray(Image.open(src).convert("RGB")).astype(np.float32)
    H, W, _ = im.shape
    for r in range(4):
        for c in range(4):
            y0, y1 = round(r * H / 4), round((r + 1) * H / 4)
            x0, x1 = round(c * W / 4), round((c + 1) * W / 4)
            yield im[y0:y1, x0:x1]


def key(cell):
    R, G, B = cell[..., 0], cell[..., 1], cell[..., 2]
    green = G - np.maximum(B, 0.55 * R)
    a = smooth(green, 18, 70) * smooth(G, 55, 140)
    a = np.clip(a, 0, 1)
    rgb = np.clip(cell / np.maximum(a[..., None], 1e-3), 0, 255) * (a[..., None] > 0)
    return rgb, a


def pixelize(rgb, a):
    s = min(rgb.shape[0], rgb.shape[1])
    rgb, a = rgb[:s, :s], a[:s, :s]
    pm = Image.fromarray(np.uint8(np.clip(rgb * a[..., None], 0, 255)))   # premultiplied, so black never bleeds in
    pa = Image.fromarray(np.uint8(a * 255))
    pm = np.asarray(pm.resize((CELL, CELL), Image.BOX)).astype(np.float32)
    pa = np.asarray(pa.resize((CELL, CELL), Image.BOX)).astype(np.float32) / 255
    col = pm / np.maximum(pa[..., None], 1e-3)
    lum = col[..., 1] * pa ** .35                                        # brighter where denser
    ramp = np.array(RAMP, np.float32)
    idx = np.clip((lum / 255) * (len(RAMP) - .01), 0, len(RAMP) - 1).astype(int)
    out = np.zeros((CELL, CELL, 4), np.uint8)
    out[..., :3] = ramp[idx]
    aq = np.round(np.clip(pa * 1.6, 0, 1) * 4) / 4                       # four alpha steps, pixel-hard edges
    aq[pa < .06] = 0
    out[..., 3] = np.uint8(aq * 255)
    return out


def main():
    src = sys.argv[1]
    frames = [pixelize(*key(c)) for c in cells(src)]
    sheet = np.zeros((CELL * 2, CELL * 8, 4), np.uint8)
    for i, f in enumerate(frames):
        r, c = divmod(i, 8)
        sheet[r * CELL:(r + 1) * CELL, c * CELL:(c + 1) * CELL] = f
        cov = (f[..., 3] > 0).mean()
        print(f"frame {i + 1:2d}: coverage {cov:5.3f}  corners {[int(f[y, x, 3]) for y in (0, -1) for x in (0, -1)]}")
    os.makedirs(OUT, exist_ok=True)
    path = os.path.join(OUT, KEY + ".webp")
    Image.fromarray(sheet).save(path, lossless=True)
    man_path = os.path.join(OUT, "manifest.json")
    man = json.load(open(man_path))
    man[KEY] = {"bytes": os.path.getsize(path), "cols": 8, "file": KEY + ".webp", "fps": FPS, "frames": N, "rows": 2, "swap": SWAP}
    json.dump(dict(sorted(man.items())), open(man_path, "w"), indent=2, sort_keys=True)
    open(man_path, "a").write("\n")
    print("wrote", path, os.path.getsize(path), "bytes")
    if "--preview" in sys.argv:
        p = sys.argv[sys.argv.index("--preview") + 1]
        bg = Image.new("RGBA", (sheet.shape[1], sheet.shape[0]), (24, 22, 30, 255))
        bg.alpha_composite(Image.fromarray(sheet))
        bg.resize((bg.width * 2, bg.height * 2), Image.NEAREST).save(p)


if __name__ == "__main__":
    main()
